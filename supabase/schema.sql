-- Apply in a dedicated Supabase project; no sample inventory is inserted.
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 team text not null, name text not null, year text not null,
 price_pence integer not null check (price_pence >= 50),
 sizes text[] not null default '{}', badge text not null default '',
 color text not null default '#e9eee6', active boolean not null default false,
 constraint valid_sizes check (sizes <@ array['S','M','L','XL']::text[])
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id),
 status text not null default 'pending' check (status in ('pending','paid','cancelled','refunded')),
 total_pence integer not null check (total_pence >= 0),
 currency text not null default 'gbp',
 stripe_session_id text unique,
 stripe_payment_intent text,
 created_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated always as identity primary key,
 order_id uuid not null references public.orders(id) on delete cascade,
 product_id bigint not null references public.products(id),
 size text not null, quantity integer not null check (quantity between 1 and 10),
 unit_price_pence integer not null check (unit_price_pence >= 0)
);
create index if not exists orders_user_created_idx on public.orders(user_id,created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
revoke all on public.products,public.orders,public.order_items from anon,authenticated;
grant select on public.products to anon,authenticated;
grant select on public.orders,public.order_items to authenticated;
drop policy if exists products_public_active on public.products;
create policy products_public_active on public.products for select to anon,authenticated using(active);
drop policy if exists orders_own_read on public.orders;
create policy orders_own_read on public.orders for select to authenticated using(auth.uid()=user_id);
drop policy if exists order_items_own_read on public.order_items;
create policy order_items_own_read on public.order_items for select to authenticated using(exists(select 1 from public.orders o where o.id=order_id and o.user_id=auth.uid()));
-- Webhook calls via service-role client. Function verifies order/session correspondence.
create or replace function public.mark_order_paid(p_order_id uuid,p_session_id text,p_payment_intent text)
returns void language plpgsql security invoker set search_path=public as $$
begin
 update public.orders set status='paid',stripe_payment_intent=p_payment_intent
 where id=p_order_id and stripe_session_id=p_session_id and status='pending';
 if not found and not exists(select 1 from public.orders where id=p_order_id and stripe_session_id=p_session_id and status='paid') then
 raise exception 'Order/session mismatch';
 end if;
end;$$;
revoke all on function public.mark_order_paid(uuid,text,text) from public,anon,authenticated;
grant execute on function public.mark_order_paid(uuid,text,text) to service_role;
